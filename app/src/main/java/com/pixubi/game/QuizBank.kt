    fun total(topic: QuizTopic): Int = questions.count { it.topic == topic }

    fun questionsFor(topic: QuizTopic): List<QuizQuestion> = questions.filter { it.topic == topic }

    /** Random 5-question round: unique questions and shuffled answers per attempt. */
    fun newRound(topic: QuizTopic, count: Int = 5, random: Random = Random.Default): List<QuizQuestion> {
        require(count > 0)
        return questionsFor(topic).shuffled(random).take(count).map { original ->
            val indices = (0..3).shuffled(random)
            original.copy(
                answers = indices.map { original.answers[it] },
                correctIndex = indices.indexOf(original.correctIndex)
            )
        }
    }
